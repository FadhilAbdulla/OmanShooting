export type Tab = { href: string; label: string; icon: string; badge?: number; prefixes?: string[] };
export type SheetItem = { label: string; icon: string; href?: string; action?: "logout" | "locale" };

/** Phone-only tab bar, like a native app. Desktop keeps the normal header navigation. */
export function BottomNav({ tabs, more, locale, wide = false, logoutTo = "/" }: { tabs: Tab[]; more?: SheetItem[]; locale?: string; wide?: boolean; logoutTo?: string }) {
  const moreLabel = locale === "ar" ? "المزيد" : "More";
  // Hidden from md (site) or lg (admin, whose sidebar appears at lg)
  const hide = wide ? "lg:hidden" : "md:hidden";
  const path = usePathname();
  const r = useRouter();
  const [open, setOpen] = useState(false);
  useEffect(() => setOpen(false), [path]);
  // Focused flows (onboarding) run full-screen without the tab bar
  if (path.startsWith("/register")) return null;

  async function run(item: SheetItem) {
    if (item.action === "logout") {
      await fetch("/api/auth/logout", { method: "POST" });
      window.location.href = logoutTo;
    } else if (item.action === "locale") {
      await fetch("/api/locale", { method: "POST", body: JSON.stringify({ locale: locale === "ar" ? "en" : "ar" }) });
      setOpen(false);
      r.refresh();
    }
  }

  return (
    <>
      {open && more && (
        <div className={cn("fixed inset-0 z-50", hide)} onClick={() => setOpen(false)}>
          <div className="absolute inset-0 bg-black/40" />
          <div className="absolute inset-x-0 bottom-0 rounded-t-3xl bg-white p-4 pb-[calc(1rem+env(safe-area-inset-bottom))] shadow-2xl" onClick={(e) => e.stopPropagation()}>
            <div className="mx-auto mb-3 h-1.5 w-12 rounded-full bg-sand-300" />
            <ul className="divide-y divide-sand-100">
              {more.map((m) => (
                <li key={m.label}>
                  {m.href ? (
                    <Link href={m.href} className="flex items-center gap-3 px-2 py-3.5 text-base text-stone-800"><Icon name={m.icon} className="h-5 w-5 text-brand-600" />{m.label}</Link>
                  ) : (
                    <button onClick={() => run(m)} className="flex w-full items-center gap-3 px-2 py-3.5 text-start text-base text-stone-800"><Icon name={m.icon} className="h-5 w-5 text-brand-600" />{m.label}</button>
                  )}
                </li>
              ))}
            </ul>
          </div>
        </div>
      )}
      <nav className={cn("fixed inset-x-0 bottom-0 z-40 border-t border-sand-200 bg-white/95 pb-[env(safe-area-inset-bottom)] shadow-[0_-4px_16px_rgba(0,0,0,0.06)] backdrop-blur no-print", hide)} aria-label="Main">
        <ul className="flex">
          {tabs.map((t) => {
            const active = path === t.href || !!t.prefixes?.some((p) => path.startsWith(p));
            return (
              <li key={t.label} className="flex-1">
                <Link href={t.href} aria-current={active ? "page" : undefined}
                  className={cn("relative flex flex-col items-center gap-0.5 pb-2 pt-2.5 text-[11px] font-medium", active ? "text-brand-600" : "text-stone-500")}>
                  {active && <span className="absolute top-0 h-0.5 w-8 rounded-full bg-brand-500" />}
                  <span className="relative">
                    <Icon name={t.icon} />
                    {!!t.badge && <span className="absolute -end-2 -top-1 flex h-4 min-w-4 items-center justify-center rounded-full bg-brand-500 px-1 text-[10px] font-bold text-white">{t.badge}</span>}
                  </span>
                  {t.label}
                </Link>
              </li>
            );
          })}
          {more && (
            <li className="flex-1">
              <button onClick={() => setOpen(true)} className="flex w-full flex-col items-center gap-0.5 pb-2 pt-2.5 text-[11px] font-medium text-stone-500">
                <Icon name="more" />{moreLabel}
              </button>
            </li>
          )}
        </ul>
      </nav>
    </>
  );
}
